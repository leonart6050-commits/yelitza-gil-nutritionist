const getNestedValue = (source, path) =>
  path.split(".").reduce((value, key) => (value ? value[key] : undefined), source);

const getLanguage = () => {
  const stored = localStorage.getItem("siteLanguage");
  return translations[stored] ? stored : "es";
};

const setContactLinks = (language) => {
  const message = contact.whatsappMessage[language] || contact.whatsappMessage.es;
  const whatsappUrl = `https://wa.me/${contact.whatsappNumber}?text=${encodeURIComponent(message)}`;
  const instagramUrl = `https://www.instagram.com/${contact.instagramHandle}/`;
  const emailUrl = `mailto:${contact.email}`;

  document.querySelectorAll('[data-contact="whatsapp"]').forEach((link) => {
    link.href = whatsappUrl;
    link.target = "_blank";
    link.rel = "noopener noreferrer";
  });

  document.querySelectorAll('[data-contact="instagram"]').forEach((link) => {
    link.href = instagramUrl;
    link.target = "_blank";
    link.rel = "noopener noreferrer";
  });

  document.querySelectorAll('[data-contact="email"]').forEach((link) => {
    link.href = emailUrl;
  });

  document.querySelectorAll('[data-fill="phone"]').forEach((item) => {
    item.textContent = contact.phoneDisplay;
  });

  document.querySelectorAll('[data-fill="instagram"]').forEach((item) => {
    item.textContent = `@${contact.instagramHandle}`;
  });

  document.querySelectorAll('[data-fill="email"]').forEach((item) => {
    item.textContent = contact.email;
  });
};

const applyLanguage = (language) => {
  const dictionary = translations[language] || translations.es;
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = getNestedValue(dictionary, node.dataset.i18n);
    if (value) node.textContent = value;
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((node) => {
    node.dataset.i18nAttr.split(",").forEach((pair) => {
      const [attribute, key] = pair.split(":").map((item) => item.trim());
      const value = getNestedValue(dictionary, key);
      if (attribute && value) node.setAttribute(attribute, value);
    });
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === language));
  });

  const titleNode = document.querySelector("title");
  const title = titleNode ? getNestedValue(dictionary, titleNode.dataset.i18n || "") : "";
  if (title) document.title = title;

  setContactLinks(language);
};

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => {
    localStorage.setItem("siteLanguage", button.dataset.lang);
    applyLanguage(button.dataset.lang);
  });
});

applyLanguage(getLanguage());
